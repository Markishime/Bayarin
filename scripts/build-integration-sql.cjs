// Generate the additive deployment bundle for the existing Bayarin database.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const directory = path.join(root, 'supabase/migrations');
const migrations = fs.readdirSync(directory).filter(name => /^20260905.*\.sql$/.test(name)).sort();
const sql = '-- Bayarin integration update. Requires the existing 20260903 and 20260904 migrations.\n-- Generated by node scripts/build-integration-sql.cjs; no account or household data is reset.\nbegin;\n\n' + migrations.map(name => `-- ${name}\n${fs.readFileSync(path.join(directory, name), 'utf8')}\n`).join('\n') + "\nnotify pgrst, 'reload schema';\ncommit;\n";
fs.writeFileSync(path.join(root, 'supabase/deploy-integrations.sql'), sql);
console.log(`Prepared ${migrations.length} integration migrations in supabase/deploy-integrations.sql`);
